def add_swrl_rules(base_owl_path, out_owl_path):
    """Загружает базовую онтологию в owlready2, добавляет SWRL-правила, сохраняет RDF/XML."""
    import owlready2
    world = owlready2.World()
    onto_ = world.get_ontology("file://" + base_owl_path).load()
    with onto_:
        for name, comment, text in SWRL_RULES:
            rule = owlready2.Imp(name)
            rule.set_as_rule(text)
            rule.label = [owlready2.locstr(name, lang="ru")]
            rule.comment = [owlready2.locstr(comment, lang="ru")]
    onto_.save(file=out_owl_path, format="rdfxml")


